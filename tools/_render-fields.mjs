/**
 * Suffix naming a MACHINE-DERIVED scalar twin. Deliberately not `_text`:
 * some entries author their own prose for a structured value (e.g.
 * encounter-building.json's `budget_band_text`), and keeping the namespaces
 * separate lets the generator own `_display` completely without overwriting
 * authored words.
 */
export const DERIVED_SUFFIX = '_display';

/** Suffix reserved for an AUTHORED prose rendering of a structured value. */
export const AUTHORED_SUFFIX = '_text';

/** Provenance bookkeeping, folded into one "Provenance Notes" column. */
export const PROVENANCE_KEYS = ['custom_fields', 'derived_from', 'omissions'];

/** The two aggregate columns the builder derives. */
export const DETAILS_KEY = 'details' + DERIVED_SUFFIX;
export const PROVENANCE_KEY = 'provenance' + DERIVED_SUFFIX;

/**
 * displayKeyFor names the scalar property key a manifest category must
 * declare to display data key `key`: the key itself when scalar, its
 * authored `<key>_text` if present, else the derived `<key>_display`. Pure,
 * so the builder and the test agree without sharing state.
 *
 * `flattened` is the set of data keys carrying reference markup anywhere in
 * the file; those always resolve to the derived twin regardless of shape,
 * since only the generated twin is flattened.
 *
 * The verdict is per FILE, not per entry — a per-entry verdict would declare
 * the bare key whenever the first carrier happened to be marker-free, and
 * every later marker-bearing entry in that column would print raw markup.
 */
export function displayKeyFor(properties, key, flattened) {
  const v = (properties || {})[key];
  if (v === undefined || v === null) return null;
  const forced = flattened instanceof Set ? flattened.has(key) : Boolean(flattened);
  if (!forced) {
    if (isScalar(v)) return key;
    if (typeof properties[key + AUTHORED_SUFFIX] === 'string') return key + AUTHORED_SUFFIX;
  }
  return key + DERIVED_SUFFIX;
}

/**
 * columnsNeedingFlattening returns the category's column keys that carry
 * reference markup in at least one entry — the keys whose manifest field must
 * point at a flattened twin. Also checks the authored `_text` phrasing, which
 * a twin would otherwise be built from.
 */
export function columnsNeedingFlattening(items, category) {
  const hit = new Set();
  for (const [dataKey] of category?.columns || []) {
    const found = items.some((it) => {
      const p = it.properties || {};
      if (p[dataKey] === undefined) return false;
      return hasRefMarkers(renderValue(p[dataKey])) || hasRefMarkers(p[dataKey + AUTHORED_SUFFIX]);
    });
    if (found) hit.add(dataKey);
  }
  return hit;
}

/**
 * foldEntries renders a set of properties into one "k — v · k — v" scalar,
 * for the two aggregate columns (see CATEGORIES). Always flattened: the
 * output is only ever printed by Chronicle, never read structurally.
 */
export function foldEntries(properties, keys) {
  return flattenRefs(
    keys
      .map((k) => [k, renderValue(properties[k])])
      .filter(([, s]) => s !== '')
      .map(([k, s]) => `${humanKey(k)} — ${s}`)
      .join(' · '),
  );
}

/** Longest summary we will derive before truncating. */
export const SUMMARY_MAX = 180;

/**
 * deriveSummary produces the one-line `summary` the list table's Summary
 * column renders (system_pages.templ prints item.Summary for every row).
 * First sentence of the description, truncated on a word boundary, so it
 * cannot drift from the description it summarizes; an entry with its own
 * non-empty summary keeps it.
 */
export function deriveSummary(description) {
  const text = String(description || '').replace(/\s+/g, ' ').trim();
  if (!text) return '';
  if (text.length <= SUMMARY_MAX) return text;

  // Prefer a sentence boundary that lands inside the budget.
  const stop = text.slice(0, SUMMARY_MAX + 1).search(/[.!?](\s|$)/);
  if (stop > 40) return text.slice(0, stop + 1);

  const cut = text.lastIndexOf(' ', SUMMARY_MAX - 1);
  return text.slice(0, cut > 40 ? cut : SUMMARY_MAX - 1).trimEnd() + '…';
}

