// _render-fields.mjs — defines what Chronicle's reference browser can
// display, and how this package's structured data is flattened for it.
//
// Chronicle renders a property via propString(props, key) =
// fmt.Sprintf("%v", props[key]), for every key in a manifest category's
// `fields`. A field key MUST exist in the data and hold a scalar: a missing
// key renders as a silent blank, and a non-scalar prints Go syntax garbage
// (`map[…]`, `<nil>`).
//
// Where an entry's substance is nested, the structured value stays put
// (widgets/Foundry sync read it) and this module derives a scalar
// `<key>_display` twin for the manifest to point at instead — generated by
// build-render-fields.mjs, pinned by test-render-contract.mjs. The
// `_display` suffix (not `_text`) avoids colliding with authored
// `<key>_text` fields.

// ---------------------------------------------------------------------------
// Reference markup
// ---------------------------------------------------------------------------
//
// This package's text fields carry `{@category term}` / `{@category
// term|label}` cross-reference markup (CLAUDE.md -> "@Reference Syntax").
// Widgets resolve it via reference-renderer.js into a tooltip span; Chronicle's
// reference browser has no such step and prints it as literal text
// (system_pages.templ's propString / item.Summary). So the STRUCTURED value
// keeps its markers (widgets need them), and the generated `<key>_display`
// twin — all Chronicle ever sees — carries the resolved text. A key whose
// value contains a marker gets a twin even when already scalar.

/**
 * REF_MARKER matches one reference marker. Must stay character-for-character
 * identical to REF_PATTERN in widgets/reference-renderer.js, or the twin and
 * the widget disagree about what a marker is. test-render-contract.mjs pins
 * them against each other by reading the widget source.
 */
export const REF_MARKER_SOURCE = '\\{@(\\w+)\\s+([^|}]+)(?:\\|([^}]+))?\\}';

/**
 * flattenRefs resolves reference markup down to the words it displays:
 *
 *   "{@combat dying}"             -> "dying"
 *   "{@condition taunted|taunts}" -> "taunts"
 *
 * i.e. the label reference-renderer.js puts in its tooltip span, minus the
 * span. Non-strings and marker-free strings pass through unchanged. Resolves
 * from the marker's own text, not a glossary lookup, so the sentence stays
 * grammatical ("{@combat dying}" reads as "dying", not the glossary's
 * title-cased "Dying").
 */
export function flattenRefs(text) {
  if (typeof text !== 'string' || !text.includes('{@')) return text;
  return text.replace(new RegExp(REF_MARKER_SOURCE, 'g'), (_m, _cat, term, label) =>
    String(label ?? term).trim(),
  );
}

/** True when a value still carries markup Chronicle would print literally. */
export function hasRefMarkers(v) {
  return typeof v === 'string' && v.includes('{@');
}

// ---------------------------------------------------------------------------
// Scalar rendering
// ---------------------------------------------------------------------------

/** True for the JSON types propString can format into human text. */
export function isScalar(v) {
  return typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean';
}

/** "stamina_per_level" -> "stamina per level" — labels inside a rendered blob. */
function humanKey(k) {
  return k.replace(/_/g, ' ');
}

// Keys that lead a rendered object (its title) and keys that form its body.
// Checked in order, so {name, description} reads "Name — description" rather
// than "name: Name; description: …".
const LEAD_KEYS = ['name', 'label', 'title', 'term'];
const BODY_KEYS = ['description', 'text', 'note'];

/**
 * renderValue turns any JSON value into one line of human-readable text.
 * Deliberately generic rather than per-file, so there's no bespoke formatter
 * to forget to update. Deterministic, so the drift test can recompute it.
 *
 *   scalar            -> "5"
 *   [scalars]         -> "Attack, Magic, Melee"
 *   {name, cost, description}
 *                     -> "Beast Legs (cost 1) — Your powerful legs …"
 *   [objects]         -> the above, joined with " · "
 *   {a: 1, b: 2}      -> "a: 1; b: 2"
 *
 * Returns "" for null/undefined and for empty arrays/objects, which callers
 * treat as "omit the key entirely" — an absent key renders as a skipped detail
 * row, whereas a present-but-empty one would render as a blank cell.
 */
export function renderValue(v) {
  if (v === null || v === undefined) return '';
  if (isScalar(v)) return String(v);

  if (Array.isArray(v)) {
    const parts = v.map(renderValue).filter((s) => s !== '');
    if (!parts.length) return '';
    // A list of plain scalars reads as a comma list; anything richer gets the
    // stronger separator so the commas inside each part stay legible.
    return v.every(isScalar) ? parts.join(', ') : parts.join(' · ');
  }

  if (typeof v === 'object') {
    const entries = Object.entries(v).filter(([, val]) => val !== null && val !== undefined);
    if (!entries.length) return '';
    const obj = Object.fromEntries(entries);

    const leadKey = LEAD_KEYS.find((k) => typeof obj[k] === 'string' && obj[k] !== '');
    const bodyKey = BODY_KEYS.find((k) => typeof obj[k] === 'string' && obj[k] !== '');

    const used = new Set([leadKey, bodyKey].filter(Boolean));
    const rest = entries
      .filter(([k]) => !used.has(k))
      .map(([k, val]) => {
        const s = renderValue(val);
        return s === '' ? '' : `${humanKey(k)}: ${s}`;
      })
      .filter((s) => s !== '');

    if (!leadKey) return rest.join('; ');

    // "Lead (rest) — body" when there is a body to set off; "Lead — rest" when
    // there isn't, so an object that is all attributes (a kit's signature
    // ability) doesn't read as one long parenthetical.
    if (!bodyKey) return rest.length ? `${obj[leadKey]} — ${rest.join('; ')}` : obj[leadKey];
    let out = obj[leadKey];
    if (rest.length) out += ` (${rest.join('; ')})`;
    return `${out} — ${obj[bodyKey]}`;
  }

  return String(v);
}

